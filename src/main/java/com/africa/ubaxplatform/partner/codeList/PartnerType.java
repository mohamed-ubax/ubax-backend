/** Type de partenaire souhaitant rejoindre la plateforme UBAX. */
public enum PartnerType {
  /** Agence immobilière proposant des biens à la vente ou à la location. */
  AGENCE_IMMOBILIERE,

  /** Établissement hôtelier (hôtel, résidence, apart-hôtel). */
  HOTEL
}

/** Promoteur immobilier développant des programmes neufs ou des lotissements. */
// PROMOTEUR_IMMOBILIER,

/** Notaire assurant la sécurité juridique des transactions immobilières. */
// NOTAIRE,

/** Syndic de copropriété gérant des immeubles collectifs. */
// SYNDIC,

/** Société de construction, rénovation ou travaux du bâtiment. */
// CONSTRUCTION_RENOVATION,

/** Expert immobilier ou évaluateur agréé pour l'estimation de biens. */
// EXPERTISE_EVALUATION,

/** Institution financière (banque, microfinance, fintech) proposant des crédits immobiliers. */
// FINANCEMENT,

/** Compagnie d'assurance proposant des produits liés à l'immobilier. */
// ASSURANCE,

/** Géomètre-expert pour le bornage et les plans fonciers. */
// GEOMETRE,

/** Autre type de partenaire non listé. */
// AUTRE
